-- Comfortable life: таблицы для Cloudflare D1. Выполняется один раз (консоль D1 → Console, вставить целиком).
CREATE TABLE IF NOT EXISTS acc (
  id TEXT PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL DEFAULT '',
  salt TEXT, ph TEXT,
  rec_salt TEXT, rec_h TEXT,
  pub TEXT, w_pw TEXT, w_rec TEXT, w_priv TEXT, prof TEXT,
  verified INTEGER NOT NULL DEFAULT 0,
  fid TEXT NOT NULL DEFAULT '',
  fails INTEGER NOT NULL DEFAULT 0, lock_until INTEGER NOT NULL DEFAULT 0,
  join_fails INTEGER NOT NULL DEFAULT 0, join_lock INTEGER NOT NULL DEFAULT 0,
  code_h TEXT, code_exp INTEGER NOT NULL DEFAULT 0, code_tries INTEGER NOT NULL DEFAULT 0, last_mail INTEGER NOT NULL DEFAULT 0,
  ya TEXT,
  created INTEGER
);
CREATE TABLE IF NOT EXISTS sess (h TEXT PRIMARY KEY, aid TEXT NOT NULL, exp INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS sess_aid ON sess(aid);
CREATE TABLE IF NOT EXISTS fam (
  fid TEXT PRIMARY KEY,
  owner TEXT,
  rev INTEGER NOT NULL DEFAULT 0,
  iv TEXT NOT NULL DEFAULT '', ct TEXT NOT NULL DEFAULT '',
  kver INTEGER NOT NULL DEFAULT 0,
  need_rot INTEGER NOT NULL DEFAULT 0,
  code TEXT, code_exp INTEGER NOT NULL DEFAULT 0,
  created INTEGER
);
CREATE UNIQUE INDEX IF NOT EXISTS fam_code ON fam(code);
CREATE TABLE IF NOT EXISTS mem (
  fid TEXT NOT NULL, aid TEXT NOT NULL,
  wrap TEXT,
  pending INTEGER NOT NULL DEFAULT 0,
  joined INTEGER,
  PRIMARY KEY (fid, aid)
);
CREATE INDEX IF NOT EXISTS mem_aid ON mem(aid);
CREATE TABLE IF NOT EXISTS inv (
  aid TEXT NOT NULL, fid TEXT NOT NULL, from_aid TEXT, from_name TEXT, ts INTEGER,
  PRIMARY KEY (aid, fid)
);
CREATE TABLE IF NOT EXISTS ai_use (aid TEXT NOT NULL, day TEXT NOT NULL, n INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (aid, day));
CREATE TABLE IF NOT EXISTS yast (state TEXT PRIMARY KEY, aid TEXT, ret TEXT, exp INTEGER);
CREATE TABLE IF NOT EXISTS rl (k TEXT PRIMARY KEY, n INTEGER NOT NULL, t INTEGER NOT NULL);
